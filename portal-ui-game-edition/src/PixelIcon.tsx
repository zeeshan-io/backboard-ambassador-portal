export function PixelIcon({
  name,
  size = 18,
  className,
  label,
}: {
  name: PixelIconName
  size?: number
  className?: string
  label?: string
}) {
  const pattern = iconPatterns[name]

  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 8 8"
      shapeRendering="crispEdges"
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
    >
      {pattern.flatMap((row, y) =>
        [...row].map((cell, x) =>
          cell === '1' ? <rect x={x} y={y} width="1" height="1" fill="currentColor" key={`${x}-${y}`} /> : null,
        ),
      )}
    </svg>
  )
}
